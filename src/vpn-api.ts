// Gluetun OpenVPN health endpoint — confirmed against gluetun HTTP API docs.
// GET /v1/openvpn/status returns { status: 'running' | 'stopped' }.
// The more general /v1/vpn/status covers WireGuard too (v2 path).
const GLUETUN_HEALTH_URL = 'http://gluetun:8000/v1/openvpn/status';

export type VpnVerifyStatus =
  | 'vpn_bridge_active'
  | 'vpn_bridge_unreachable'
  | 'passthrough';

export type VpnApiDeps = {
  configPath: string;
  writeToken: string | undefined;
  transmissionConfig: TransmissionConfig;
};

function parseBearerToken(header: string | null): string | null {
  if (!header) return null;
  const [scheme, token] = header.split(' ');
  if (scheme?.toLowerCase() !== 'bearer' || !token) return null;
  return token;
}

function checkWriteAuth(
  request: Request,
  writeToken: string | undefined,
): Response | null {
  if (!writeToken) {
    return Response.json(
      { error: 'config writes are disabled' },
      { status: 403 },
    );
  }
  const bearer = parseBearerToken(request.headers.get('authorization'));
  if (!bearer) {
    return Response.json({ error: 'missing bearer token' }, { status: 401 });
  }
  if (bearer !== writeToken) {
    return Response.json({ error: 'forbidden' }, { status: 403 });
  }
  return null;
}

async function readTrustedOrigins(configDir: string): Promise<string[]> {
  const file = Bun.file(join(configDir, 'web', 'trusted-origins.json'));
  if (!(await file.exists())) return [];
  try {
    const raw: unknown = await file.json();
    if (!Array.isArray(raw)) return [];
    return (raw as unknown[]).filter((x): x is string => typeof x === 'string');
  } catch {
    return [];
  }
}

function composePath(configDir: string): string {
  return join(vpnDir(configDir), 'compose.synology.yml');
}

