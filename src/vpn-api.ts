async function handleProfileUpload(
  request: Request,
  configDir: string,
  configPath: string,
): Promise<Response> {
  const bytes = await request.arrayBuffer();
  if (bytes.byteLength === 0) {
    return Response.json({ error: 'Request body is empty.' }, { status: 400 });
  }
  const text = new TextDecoder()
    .decode(new Uint8Array(bytes).slice(0, 16))
    .trimStart();
  const isValidOvpn = text.startsWith('client') || text.startsWith('proto');
  if (!isValidOvpn) {
    return Response.json(
      { error: 'Invalid .ovpn file: must begin with "client" or "proto".' },
      { status: 400 },
    );
  }

  await mkdir(vpnDir(configDir), { recursive: true });
  const profilePath = activeProfilePath(configDir);
  const tempPath = `${profilePath}.${process.pid}.${randomUUID()}.tmp`;
  writeFileSync(tempPath, new Uint8Array(bytes));
  await rename(tempPath, profilePath);

  const existingManifest = await readVpnManifest(configDir);
  const manifest: VpnManifest = {
    uploadedAt: new Date().toISOString(),
    provider: 'custom',
    hasCredentials: existingManifest?.hasCredentials ?? false,
  };
  await writeVpnManifest(configDir, manifest);

  // update config downloaderNetwork
  const baseOnDisk = await readConfigFileRecord(configPath);
  const existingDn =
    baseOnDisk.downloaderNetwork &&
    typeof baseOnDisk.downloaderNetwork === 'object' &&
    !Array.isArray(baseOnDisk.downloaderNetwork)
      ? (baseOnDisk.downloaderNetwork as Record<string, unknown>)
      : {};
  writeConfigAtomically(configPath, {
    ...baseOnDisk,
    downloaderNetwork: {
      ...existingDn,
      mode: 'vpn_bridge',
      status: 'pending_verify',
    },
  });

  await generateComposeArtifact(configDir);
  console.log(
    `[vpn] profile saved — size: ${String(bytes.byteLength)}; compose artifacts regenerated`,
  );
  return Response.json({ ok: true, manifest });
}

async function handleCredentialsSave(
  request: Request,
  configDir: string,
): Promise<Response> {
  let body: unknown;
  try {
    body = await request.json();
  } catch {
    return Response.json(
      { error: 'Request body must be JSON.' },
      { status: 400 },
    );
  }
  if (
    !body ||
    typeof body !== 'object' ||
    Array.isArray(body) ||
    typeof (body as Record<string, unknown>).username !== 'string' ||
    typeof (body as Record<string, unknown>).password !== 'string'
  ) {
    return Response.json(
      { error: 'Body must be { username: string, password: string }.' },
      { status: 400 },
    );
  }
  const { username, password } = body as { username: string; password: string };
  if (!username.trim() || !password.trim()) {
    return Response.json(
      { error: 'username and password must be non-empty strings.' },
      { status: 400 },
    );
  }

  await mkdir(vpnDir(configDir), { recursive: true });
  const credsPath = credentialsPath(configDir);
  const credsContent = `${username}\n${password}\n`;
  writeFileSync(credsPath, credsContent, { encoding: 'utf8', mode: 0o600 });

  const existingManifest = await readVpnManifest(configDir);
  const manifest: VpnManifest = {
    uploadedAt: existingManifest?.uploadedAt ?? new Date().toISOString(),
    provider: existingManifest?.provider ?? 'custom',
    hasCredentials: true,
  };
  await writeVpnManifest(configDir, manifest);

  await generateComposeArtifact(configDir);
  console.log(
    `[vpn] credentials saved (username: ${username}); compose artifacts regenerated`,
  );
  return Response.json({ ok: true });
}

async function handleComposeServe(configDir: string): Promise<Response> {
  const path = composePath(configDir);
  const file = Bun.file(path);
  if (!(await file.exists())) {
    console.log('[vpn] compose artifact requested — not found');
    return Response.json(
      { error: 'No VPN profile saved yet. Upload a profile first.' },
      { status: 404 },
    );
  }
  console.log('[vpn] compose artifact served');
  const text = await file.text();
  return new Response(text, {
    headers: {
      'Content-Type': 'application/yaml',
      'Content-Disposition': 'attachment; filename=compose.synology.yml',
    },
  });
}

async function handleVerify(
  configDir: string,
  transmissionConfig: TransmissionConfig,
): Promise<Response> {
  const manifest = await readVpnManifest(configDir);
  if (!manifest?.hasCredentials) {
    console.log('[vpn] verify — no credentials saved; result: passthrough');
    return Response.json({ status: 'passthrough' satisfies VpnVerifyStatus });
  }

  let gluetunOk = false;
  let gluetunDetail = 'ok';
  let transmissionOk = false;
  let transmissionDetail = 'ok';

  try {
    const gluetunRes = await fetch(GLUETUN_HEALTH_URL, {
      signal: AbortSignal.timeout(10_000),
    });
    gluetunOk = gluetunRes.ok;
    if (!gluetunOk) gluetunDetail = `http ${String(gluetunRes.status)}`;
  } catch (err) {
    gluetunDetail = `error: ${err instanceof Error ? err.message : String(err)}`;
  }

  try {
    const result = await fetchSessionInfo(transmissionConfig);
    if (!('ok' in result) || result.ok !== false) {
      transmissionOk = true;
    } else {
      transmissionDetail = `error: ${result.message}`;
    }
  } catch (err) {
    transmissionDetail = `error: ${err instanceof Error ? err.message : String(err)}`;
  }

  const status: VpnVerifyStatus =
    gluetunOk && transmissionOk
      ? 'vpn_bridge_active'
      : 'vpn_bridge_unreachable';

  console.log(
    `[vpn] verify — gluetun: ${gluetunDetail}; transmission: ${transmissionDetail}; result: ${status}`,
  );
  return Response.json({ status });
}

export async function handleVpnRoute(
  request: Request,
  deps: VpnApiDeps,
): Promise<Response | null> {
  const { configPath, writeToken, transmissionConfig } = deps;
  const configDir = configPath.replace(/\/[^/]+$/, '');
  const url = new URL(request.url);
  const path = url.pathname;

  if (path === '/api/vpn/profile' && request.method === 'POST') {
    const authError = checkWriteAuth(request, writeToken);
    if (authError) return authError;
    return handleProfileUpload(request, configDir, configPath);
  }

  if (path === '/api/vpn/credentials' && request.method === 'POST') {
    const authError = checkWriteAuth(request, writeToken);
    if (authError) return authError;
    return handleCredentialsSave(request, configDir);
  }

  if (path === '/api/vpn/compose' && request.method === 'GET') {
    return handleComposeServe(configDir);
  }

  if (path === '/api/vpn/verify' && request.method === 'POST') {
    const authError = checkWriteAuth(request, writeToken);
    if (authError) return authError;
    return handleVerify(configDir, transmissionConfig);
  }

  return null;
}
